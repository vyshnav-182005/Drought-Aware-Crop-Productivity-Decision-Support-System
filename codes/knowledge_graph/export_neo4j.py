"""
Export the knowledge graph for Neo4j.

Writes outputs/knowledge_graph/neo4j/:
  nodes_<Label>.csv            one file per node type (key + properties)
  rels_<RELATION>.csv          one file per relationship type (start key, end key, properties)
  import.cypher                LOAD CSV script: constraints, nodes, relationships

Load it (Neo4j Desktop / Aura / docker):
  1. copy the neo4j/ folder's CSVs into the database's import/ directory
  2. run import.cypher with:  cypher-shell -f import.cypher
     (in Neo4j Browser, prefix each relationship statement with :auto, since
     they use CALL {...} IN TRANSACTIONS)
Or push straight from Python if the `neo4j` driver is installed:
  python codes/knowledge_graph/export_neo4j.py --uri bolt://localhost:7687 --user neo4j --password <pw>

Every node gets the property `key` (the NetworkX node id, e.g.
"ConditionDetail:onset_delay_4w") with a uniqueness constraint per label, so
GraphRAG Cypher templates can MATCH on it. Example template:

  MATCH (d:ConditionDetail {code: $condition})-[r:RECOMMENDS]->(a:Action)
  WHERE r.district = $district AND r.crop = $crop
    AND (r.season = $season OR r.season IS NULL)
  OPTIONAL MATCH (a)-[s:SUGGESTS_CROP]->(alt:Crop)
  RETURN d.name, r.soil_type, r.crop_stage, a, r.source_page, collect(alt.name)
"""
import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GRAPH_JSON = ROOT / "outputs" / "knowledge_graph" / "knowledge_graph.json"
OUT = ROOT / "outputs" / "knowledge_graph" / "neo4j"
NUMERIC = {"rainfall_normal_mm", "net_irrigated_pct", "area_kha", "pct", "year", "source_page",
           "continued_on_page", "area_ha", "production_t", "yield_t_ha", "onset_delay_weeks",
           "dry_spell_days_min", "dry_spell_days_max", "days_after_onset_max", "min_rainless_days",
           "rainless_threshold_mm", "min_days", "rainfall_mm", "monsoon_jun_sep_mm",
           "pct_departure_from_mean", "longest_dry_spell_days", "max_3day_rain_mm"}


def load():
    data = json.loads(GRAPH_JSON.read_text(encoding="utf-8"))
    nodes, rels = defaultdict(list), defaultdict(list)
    for n in data["nodes"]:
        props = {k: v for k, v in n.items() if k not in ("id", "type") and v not in (None, "")}
        nodes[n["type"]].append({"key": n["id"], **props})
    for e in data["edges"]:
        props = {k: v for k, v in e.items() if k not in ("source", "target", "key", "relation")
                 and v not in (None, "")}
        rels[e["relation"]].append({"start": e["source"], "end": e["target"], **props})
    labels = {n["id"]: n["type"] for n in data["nodes"]}
    return nodes, rels, labels


def cast(prop):
    return f"toFloat(row.{prop})" if prop in NUMERIC else (
        f"toBoolean(row.{prop})" if prop == "intercrop" else f"row.{prop}")


def write_files(nodes, rels, labels):
    OUT.mkdir(parents=True, exist_ok=True)
    cy = ["// Generated by export_neo4j.py -- run after copying the CSVs to Neo4j's import/ folder", ""]
    for label in sorted(nodes):
        cy.append(f"CREATE CONSTRAINT {label.lower()}_key IF NOT EXISTS FOR (n:{label}) REQUIRE n.key IS UNIQUE;")
    cy.append("")
    for label, rows in sorted(nodes.items()):
        cols = sorted({k for r in rows for k in r} - {"key"})
        with open(OUT / f"nodes_{label}.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=["key"] + cols)
            w.writeheader()
            w.writerows(rows)
        sets = ", ".join(f"n.{c} = {cast(c)}" for c in cols)
        cy.append(f"LOAD CSV WITH HEADERS FROM 'file:///nodes_{label}.csv' AS row\n"
                  f"MERGE (n:{label} {{key: row.key}})" + (f"\nSET {sets}" if sets else "") + ";\n")
    cy.append("")
    for rel, rows in sorted(rels.items()):
        start_l = {labels[r["start"]] for r in rows}
        end_l = {labels[r["end"]] for r in rows}
        cols = sorted({k for r in rows for k in r} - {"start", "end"})
        with open(OUT / f"rels_{rel}.csv", "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=["start", "end"] + cols)
            w.writeheader()
            w.writerows(rows)
        s = f":{next(iter(start_l))}" if len(start_l) == 1 else ""
        t = f":{next(iter(end_l))}" if len(end_l) == 1 else ""
        sets = ", ".join(f"r.{c} = {cast(c)}" for c in cols)
        cy.append(f"LOAD CSV WITH HEADERS FROM 'file:///rels_{rel}.csv' AS row\n"
                  f"CALL {{ WITH row\n  MATCH (a{s} {{key: row.start}}), (b{t} {{key: row.end}})\n"
                  f"  CREATE (a)-[r:{rel}]->(b)" + (f"\n  SET {sets}" if sets else "") +
                  "\n} IN TRANSACTIONS OF 500 ROWS;\n")
    (OUT / "import.cypher").write_text("\n".join(cy) + "\n", encoding="utf-8")
    print(f"Written {OUT}: {sum(map(len, nodes.values()))} nodes in {len(nodes)} files, "
          f"{sum(map(len, rels.values()))} relationships in {len(rels)} files, import.cypher")


def push(nodes, rels, labels, uri, user, password):
    from neo4j import GraphDatabase  # pip install neo4j
    drv = GraphDatabase.driver(uri, auth=(user, password))
    with drv.session() as s:
        for label in nodes:
            s.run(f"CREATE CONSTRAINT {label.lower()}_key IF NOT EXISTS FOR (n:{label}) REQUIRE n.key IS UNIQUE")
        for label, rows in nodes.items():
            s.run(f"UNWIND $rows AS row MERGE (n:{label} {{key: row.key}}) SET n += row", rows=rows)
        for rel, rows in rels.items():
            for i in range(0, len(rows), 500):
                batch = [{"start": r["start"], "end": r["end"],
                          "props": {k: v for k, v in r.items() if k not in ("start", "end")}}
                         for r in rows[i:i + 500]]
                s.run(f"UNWIND $rows AS row MATCH (a {{key: row.start}}), (b {{key: row.end}}) "
                      f"CREATE (a)-[r:{rel}]->(b) SET r += row.props", rows=batch)
    drv.close()
    print(f"Pushed to {uri}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--uri")
    p.add_argument("--user", default="neo4j")
    p.add_argument("--password")
    a = p.parse_args()
    nodes, rels, labels = load()
    write_files(nodes, rels, labels)
    if a.uri:
        push(nodes, rels, labels, a.uri, a.user, a.password)


if __name__ == "__main__":
    main()
